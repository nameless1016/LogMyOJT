import sqlparse
from decimal import Decimal
from django.contrib.auth.models import User
from django.core.management.base import BaseCommand, CommandError
from apps.time_log import selectors


class Command(BaseCommand):
    help = "Demonstrates the SQL generated by SUBQUERY selectors for a given user."

    def add_arguments(self, parser):
        parser.add_argument("username", type=str, help="Username of the student")

    def handle(self, *args, **options):
        username = options["username"]
        try:
            user = User.objects.get(username=username)
        except User.DoesNotExist:
            raise CommandError(f"User with username '{username}' does not exist.")

        self.stdout.write(self.style.MIGRATE_HEADING("=================================================="))
        self.stdout.write(self.style.MIGRATE_HEADING("   SQL SUBQUERY 1: Above-Average Days"))
        self.stdout.write(self.style.MIGRATE_HEADING("=================================================="))
        self.stdout.write("ORM Code:")
        self.stdout.write(
            self.style.SUCCESS(
                "  avg_subquery = own_logs.values('placement__user').annotate(avg=Avg('hours_computed')).values('avg')[:1]\n"
                "  own_logs.select_related('placement').filter(hours_computed__gt=Subquery(avg_subquery))"
            )
        )
        self.stdout.write("")

        avg_val = selectors.average_hours(user)
        self.stdout.write(self.style.MIGRATE_LABEL(f"Inner Query Scalar Result (User's Average Hours): {avg_val} h"))
        self.stdout.write("")

        qs_above = selectors.above_average_logs(user)
        raw_sql_above = str(qs_above.query)
        formatted_sql_above = sqlparse.format(raw_sql_above, reindent=True, keyword_case="UPPER")

        self.stdout.write(self.style.MIGRATE_LABEL("Generated SQL Query (Note nested SELECT in WHERE clause):"))
        self.stdout.write(formatted_sql_above)
        self.stdout.write("")

        rows_above = list(qs_above[:5])
        if rows_above:
            self.stdout.write(self.style.MIGRATE_LABEL(f"Executed Result (First {len(rows_above)} above-average logs):"))
            self.stdout.write("-" * 65)
            self.stdout.write(f"{'Date':<12} | {'Hours':<8} | {'Difference':<12} | {'Company':<25}")
            self.stdout.write("-" * 65)
            avg_dec = Decimal(str(avg_val)) if avg_val else Decimal('0.00')
            for log in rows_above:
                diff = round(log.hours_computed - avg_dec, 2)
                self.stdout.write(f"{str(log.log_date):<12} | {log.hours_computed:<8} | {f'+{diff}h':<12} | {log.placement.company_name:<25}")
            self.stdout.write("-" * 65)
        else:
            self.stdout.write(self.style.WARNING("No logs strictly above the computed average found."))

        self.stdout.write("")
        self.stdout.write(self.style.MIGRATE_HEADING("=================================================="))
        self.stdout.write(self.style.MIGRATE_HEADING("   SQL SUBQUERY 2: Logs Missing Activity Note (Task 3B)"))
        self.stdout.write(self.style.MIGRATE_HEADING("=================================================="))
        self.stdout.write("ORM Code:")
        self.stdout.write(
            self.style.SUCCESS(
                "  TimeLog.objects.filter(placement__user=user).exclude(id__in=Subquery(ActivityNote.objects.values('time_log_id')))"
            )
        )
        self.stdout.write("")

        qs_missing = selectors.logs_missing_notes(user)
        raw_sql_missing = str(qs_missing.query)
        formatted_sql_missing = sqlparse.format(raw_sql_missing, reindent=True, keyword_case="UPPER")

        self.stdout.write(self.style.MIGRATE_LABEL("Generated SQL Query (WHERE NOT IN subquery):"))
        self.stdout.write(formatted_sql_missing)
        self.stdout.write("")

        rows_missing = list(qs_missing[:5])
        if rows_missing:
            self.stdout.write(self.style.MIGRATE_LABEL(f"Executed Result ({len(rows_missing)} logs without activity notes):"))
            self.stdout.write("-" * 55)
            self.stdout.write(f"{'Date':<12} | {'Hours':<8} | {'Company':<25}")
            self.stdout.write("-" * 55)
            for log in rows_missing:
                self.stdout.write(f"{str(log.log_date):<12} | {log.hours_computed:<8} | {log.placement.company_name:<25}")
            self.stdout.write("-" * 55)
        else:
            self.stdout.write(self.style.SUCCESS("All time logs have activity notes."))
