import sqlparse
from django.contrib.auth.models import User
from django.core.management.base import BaseCommand, CommandError
from apps.time_log import selectors


class Command(BaseCommand):
    help = "Demonstrates the SQL generated by the JOIN selector (select_related) for a given user."

    def add_arguments(self, parser):
        parser.add_argument("username", type=str, help="Username of the student")

    def handle(self, *args, **options):
        username = options["username"]
        try:
            user = User.objects.get(username=username)
        except User.DoesNotExist:
            raise CommandError(f"User with username '{username}' does not exist.")

        self.stdout.write(self.style.MIGRATE_HEADING("=================================================="))
        self.stdout.write(self.style.MIGRATE_HEADING("   SQL JOIN (Django ORM: select_related)"))
        self.stdout.write(self.style.MIGRATE_HEADING("=================================================="))
        self.stdout.write("ORM Code:")
        self.stdout.write(
            self.style.SUCCESS(
                "  TimeLog.objects.select_related('placement', 'activity_note')"
                ".filter(placement__user=user).order_by('-log_date', '-time_in')"
            )
        )
        self.stdout.write("")

        qs = selectors.logs_with_placement_and_note(user)
        raw_sql = str(qs.query)
        formatted_sql = sqlparse.format(
            raw_sql,
            reindent=True,
            keyword_case="UPPER",
        )

        self.stdout.write(self.style.MIGRATE_LABEL("Generated SQL Query:"))
        self.stdout.write(formatted_sql)
        self.stdout.write("")

        # Fetch sample rows to prove execution against Supabase
        logs = list(qs[:5])
        if not logs:
            self.stdout.write(self.style.WARNING(f"User '{username}' currently has no time logs recorded."))
            return

        self.stdout.write(self.style.MIGRATE_LABEL(f"Executed Result (First {len(logs)} rows from DB):"))
        self.stdout.write("-" * 88)
        header = f"{'Date':<12} | {'Company':<22} | {'Supervisor':<18} | {'Hours':<6} | {'Activity Note':<20}"
        self.stdout.write(header)
        self.stdout.write("-" * 88)

        for log in logs:
            date_str = str(log.log_date)
            company = (log.placement.company_name[:20] + "..") if len(log.placement.company_name) > 20 else log.placement.company_name
            supervisor = (log.placement.supervisor_name[:16] + "..") if len(log.placement.supervisor_name) > 16 else log.placement.supervisor_name
            hours = f"{log.hours_computed}h"
            note_raw = log.activity_note.description if hasattr(log, "activity_note") and log.activity_note else "(No note)"
            note = (note_raw[:27] + "...") if len(note_raw) > 30 else note_raw

            row = f"{date_str:<12} | {company:<22} | {supervisor:<18} | {hours:<6} | {note:<20}"
            self.stdout.write(row)

        self.stdout.write("-" * 88)
        self.stdout.write(self.style.SUCCESS(f"Successfully verified SQL JOIN execution for '{username}'."))
